// Regenerate data/career/brandLogos.ts.
//
// Two sources, in order of preference:
//
//   1. A real logo file dropped into public/brands/<brand-id>.(png|svg|webp).
//      Anything in there wins, and nothing else needs to change — the id is the
//      one in data/career/brands.ts.
//   2. The official mark geometry carried by `simple-icons`, for the brands it
//      has. The icon data there is CC0; the marks themselves remain the
//      trademarks of their owners.
//
// Brands in neither fall back to the drawn glyph in BrandMark.tsx.
//
//   node scripts/gen-brand-logos.mjs

import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, extname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as si from 'simple-icons';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// The brand ids, read straight out of the catalogue so the two cannot drift.
const src = await import(join(root, 'data/career/brands.ts')).catch(() => null);
const ids = src
  ? src.BRANDS.map(b => b.id)
  : [...(await import('node:fs')).readFileSync(join(root, 'data/career/brands.ts'), 'utf8')
      .matchAll(/B\('([a-z0-9-]+)'/g)].map(m => m[1]);

// ---- 1. files the user has dropped in ----
const dir = join(root, 'public/brands');
const files = existsSync(dir) ? readdirSync(dir) : [];
const dropped = new Map();
for (const f of files) {
  const ext = extname(f).toLowerCase();
  if (!['.png', '.svg', '.webp', '.jpg', '.jpeg'].includes(ext)) continue;
  dropped.set(basename(f, ext), f);
}

// ---- 2. simple-icons, by title or by id ----
const norm = s => 'si' + s.replace(/[^A-Za-z0-9]/g, '').replace(/^./, c => c.toUpperCase());
const NAME = {
  nike: 'Nike', adidas: 'Adidas', puma: 'Puma', 'new-balance': 'New Balance',
  'under-armour': 'Under Armour', reebok: 'Reebok', audi: 'Audi', bmw: 'BMW',
  emirates: 'Emirates', 'red-bull': 'Red Bull', dior: 'Dior', beats: 'Beats',
  movistar: 'Movistar',
};
const vector = new Map();
for (const id of ids) {
  const icon = [NAME[id], id].filter(Boolean)
    .flatMap(n => [norm(n), norm(String(n).replace(/[ -]/g, ''))])
    .map(k => si[k]).find(Boolean);
  if (icon) vector.set(id, { path: icon.path, hex: `#${icon.hex}`, title: icon.title });
}

const lines = [];
lines.push('// GENERATED by scripts/gen-brand-logos.mjs — do not edit by hand.');
lines.push('//');
lines.push('// Real brand marks. `file` is a logo image in public/brands/, and wins over');
lines.push('// everything. `path` is official mark geometry from `simple-icons` (CC0 icon');
lines.push('// data; the marks themselves remain the trademarks of their owners), drawn in a');
lines.push('// 24x24 box. A brand in neither map falls back to the drawn glyph in');
lines.push('// components/career/BrandMark.tsx.');
lines.push('//');
lines.push('// To add one: drop <brand-id>.png into public/brands/ and re-run the script.');
lines.push('');
lines.push('export interface BrandLogo {');
lines.push('  /** filename under /brands/, if a real image was supplied */');
lines.push('  file?: string;');
lines.push('  /** official mark geometry, 24x24 viewBox */');
lines.push('  path?: string;');
lines.push('  /** the brand\'s own hex, from the same source as the mark */');
lines.push('  hex?: string;');
lines.push('}');
lines.push('');
lines.push('export const BRAND_LOGOS: Record<string, BrandLogo> = {');
for (const id of ids) {
  const f = dropped.get(id);
  const v = vector.get(id);
  if (!f && !v) continue;
  const parts = [];
  if (f) parts.push(`file: ${JSON.stringify(f)}`);
  if (v) { parts.push(`hex: ${JSON.stringify(v.hex)}`); parts.push(`path: ${JSON.stringify(v.path)}`); }
  lines.push(`  ${/^[a-z][a-z0-9]*$/i.test(id) ? id : JSON.stringify(id)}: { ${parts.join(', ')} },`);
}
lines.push('};');
lines.push('');
lines.push(`/** Brands with no real mark available — they use the drawn fallback. */`);
lines.push(`export const DRAWN_ONLY: string[] = ${JSON.stringify(
  ids.filter(id => !dropped.has(id) && !vector.has(id)), null, 2).replace(/\n/g, '\n  ')};`);
lines.push('');

writeFileSync(join(root, 'data/career/brandLogos.ts'), lines.join('\n'));

const real = ids.filter(id => dropped.has(id) || vector.has(id));
console.log(`brands: ${ids.length}`);
console.log(`  image files : ${dropped.size}${dropped.size ? ` (${[...dropped.keys()].join(', ')})` : ''}`);
console.log(`  vector marks: ${vector.size} (${[...vector.keys()].join(', ')})`);
console.log(`  drawn only  : ${ids.length - real.length} (${ids.filter(id => !real.includes(id)).join(', ')})`);
