// Resolves trophy/award images for everything the copero CDN does not carry.
// Same batched pageimages approach as scripts/fetch-crests.mjs (pilicense=any
// is required — most trophy photos and award logos are non-free).
import fs from 'node:fs';

const UA = 'FootballDraft/1.0 (career-mode trophy lookup)';
const TITLE = {
  euro: 'UEFA European Championship',
  'asian-cup': 'AFC Asian Cup',
  afcon: 'Africa Cup of Nations',
  'gold-cup': 'CONCACAF Gold Cup',
  'nations-league': 'UEFA Nations League',
  'concacaf-cup': 'CONCACAF Champions Cup',
  'afc-cl': 'AFC Champions League Elite',
  'caf-cl': 'CAF Champions League',
  'ballon-dor': "Ballon d'Or",
  'the-best': 'The Best FIFA Football Awards',
  'golden-shoe': 'European Golden Shoe',
  'world-cup-golden-ball': 'FIFA World Cup awards',
  'world-cup-golden-boot': 'FIFA World Cup awards',
  'ucl-mvp': 'UEFA Champions League',
};

const url = 'https://en.wikipedia.org/w/api.php?action=query&format=json&redirects=1'
  + '&prop=pageimages&pilicense=any&piprop=original|thumbnail&pithumbsize=256&titles='
  + encodeURIComponent([...new Set(Object.values(TITLE))].join('|'));
const r = await fetch(url, { headers: { 'user-agent': UA, accept: 'application/json' } });
const j = await r.json();

const byTitle = {};
const norm = new Map();
for (const n of j?.query?.normalized ?? []) norm.set(n.to, n.from);
for (const rd of j?.query?.redirects ?? []) norm.set(rd.to, norm.get(rd.from) ?? rd.from);
for (const pid of Object.keys(j?.query?.pages ?? {})) {
  const pg = j.query.pages[pid];
  const img = pg?.original?.source || pg?.thumbnail?.source;
  if (img) byTitle[norm.get(pg.title) ?? pg.title] = img;
}

const out = {};
for (const [key, title] of Object.entries(TITLE)) {
  if (byTitle[title]) out[key] = byTitle[title];
}
const missing = Object.keys(TITLE).filter(k => !out[k]);
console.error(`resolved ${Object.keys(out).length}/${Object.keys(TITLE).length}; missing: ${missing.join(',') || 'none'}`);
fs.writeFileSync('data/career/trophy-urls.ts',
  `// Auto-generated by scripts/fetch-trophies.mjs. The copero CDN only carries
// seven trophies (see lib/career/trophies.ts); everything else is resolved from
// Wikipedia and hotlinked, since these images are non-free. Anything missing
// falls back to the drawn icon in components/career/TrophyArt.tsx.
export const TROPHY_WIKI: Record<string, string> = ${JSON.stringify(out, null, 2)};
`);
