// Deterministic fallback so unlisted names always rate the same: 70-79.
export function ratingForManager(name: string): number {
  const known = MANAGER_RATINGS[name];
  if (known) return known;
  let h = 0;
  for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) | 0;
  return 70 + (Math.abs(h) % 10);
}

// Era manager strings may list several bosses ("Roy Evans / Gérard Houllier").
export function eraManagerNames(era: TeamEra): string[] {
  if (!era.manager) return [];
  return era.manager.split('/').map(s => s.trim()).filter(Boolean);
}

// All unique managers across a team pool — the draw pool for the manager spin.
export function buildManagerPool(teams: Team[]): ManagerEntry[] {
  const out: ManagerEntry[] = [];
  const seen = new Set<string>();
  for (const team of teams) {
    for (const [eraKey, era] of Object.entries(team.eras)) {
      if (!era) continue;
      for (const name of eraManagerNames(era)) {
        if (seen.has(name)) continue;
        seen.add(name);
        out.push({
          name,
          overall: ratingForManager(name),
          teamId: team.id,
          teamName: team.name,
          teamShort: team.shortName,
          era: eraKey as EraKey,
          color: team.colors.primary,
        });
      }
    }
  }
  return out;
}
